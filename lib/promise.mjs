// 草稿里「答应要做的事」和「说已经做好了」：没做就发出去，对方会等 / 会以为好了。Claude 也会标，这里是程序兜底
const VERB = '摘|加|开|改|调|提|充|修|上线|切|删|换|配|放开|下掉|补|写|处理|弄|发';
const PROMISE = [
  new RegExp(`(弄完|搞定|弄好|改好|开好|加好|摘好|修好|调好|配好|写好|处理好|做好|好了)了?(以后|之后)?我?(就|马上|立刻|第一时间)?(告诉|通知|跟|和|发|回)你`),
  new RegExp(`我(这边)?(先|现在|马上|这就|等下|待会儿?|稍后|一会儿?|今晚|明天|下午|晚点)就?(去|来)?(看下|看一下)?[^，。,；;！!？?\\n]{0,6}?(给你|帮你|给他|帮他)?(把|给)?[^，。,；;！!？?\\n]{0,24}?(${VERB})`),
  new RegExp(`(晚点|待会儿?|一会儿?|稍后|回头|明天|今晚|下午)再?(给你|帮你|给他|帮他)(${VERB})`),
];
const DONE = [
  new RegExp(`已(经)?(给你|帮你|给他|帮他)?(把[^，。,；\\n]{0,24})?(${VERB})(好|上|掉|到|通)`),
  new RegExp(`(开好|加好|摘好|改好|调好|修好|配好|充好)了`),
];
const hits = (res, text) => res.map((re) => String(text || '').match(re)?.[0]).filter(Boolean);
export const claims = (text) => ({ promise: hits(PROMISE, text), done: hits(DONE, text) });
